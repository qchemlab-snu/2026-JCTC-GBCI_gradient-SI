"""LaTeX table of the B3LYP-optimized geometry, for the Supporting Information.

Same five-column longtable layout as ``test/supporting_information_geometries.tex``
so the block can be appended to that file. Atom names come from the shared label
map, so ``--labels`` can identify atoms the same way as the gradient table and the
figure; the default is bare element symbols, as in that file.
"""

from pathlib import Path
import argparse
import json

SCRIPT_DIR = Path(__file__).resolve().parent
GEOMETRY = SCRIPT_DIR / ".." / "dft" / "outputs" / "3hf_dft_S0_opt.xyz"
RESULT_JSON = SCRIPT_DIR / ".." / "dft" / "outputs" / "3hf_dft_S0_result.json"
LABELS_JSON = SCRIPT_DIR / "outputs" / "10_atom_labels.json"
OUTPUT_TEX = SCRIPT_DIR / "outputs" / "11_geometry_table.tex"

HEADING = r"3-Hydroxyflavone, B3LYP/6-31G(d) S$_0$ minimum"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--labels", action="store_true",
                    help="use the chemical labels (O4, C4, C1', ...) of the "
                         "figure and the gradient table instead of bare "
                         "element symbols")
    args = ap.parse_args()

    rows = []
    for line in GEOMETRY.read_text().splitlines()[2:]:
        f = line.split()
        if len(f) == 4:
            rows.append((f[0], float(f[1]), float(f[2]), float(f[3])))

    labels = json.loads(LABELS_JSON.read_text()) if LABELS_JSON.exists() else {}
    if args.labels and not labels:
        raise RuntimeError(f"run 10_make_molecule_figure.py first to write "
                           f"{LABELS_JSON}")

    energy = json.loads(RESULT_JSON.read_text())["energy_hartree"]

    lines = [
        r"% Generated by test/3HF/gbci/11_make_geometry_table.py",
        r"% Cartesian coordinates in Angstrom.",
        r"% Requires: \usepackage{longtable}",
        r"\begin{longtable}{llrrr}",
        r"\caption{",
        r"Optimized Cartesian coordinates of 3-hydroxyflavone in its electronic",
        rf"ground state, at B3LYP/6-31G(d) ($E = {energy:.6f}$ hartree). The",
        r"structure is a minimum: no imaginary frequencies were found in a",
        r"numerical Hessian at this geometry.",
        r"}\label{tab:si_3hf_geometry}\\",
        r"\hline",
        r"Geometry & Atom & $x$ & $y$ & $z$ \\",
        r"\hline",
        r"\endfirsthead",
        r"\hline",
        r"Geometry & Atom & $x$ & $y$ & $z$ \\",
        r"\hline",
        r"\endhead",
        r"\hline",
        r"\endfoot",
        rf"\multicolumn{{5}}{{l}}{{\textbf{{{HEADING}}}}}\\",
    ]
    for i, (symbol, x, y, z) in enumerate(rows):
        name = labels[str(i)] if args.labels else symbol
        lines.append(f" & {name} & {x:11.8f} & {y:11.8f} & {z:11.8f} " + r"\\")
    lines += [r"\end{longtable}"]

    OUTPUT_TEX.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\nSaved {OUTPUT_TEX}")


if __name__ == "__main__":
    main()
