"""LaTeX table of the full analytic vs finite-difference S1 gradient, for the SI.

Every Cartesian component of all 28 atoms at h = 1e-4 bohr, the step size where
the agreement is best.  Table~\\ref{tab:3hf-s1-gradient} in the main text shows
the five atoms of the intramolecular hydrogen bond out of this same campaign;
this is the whole of it, so that the largest differences -- which fall on C8a
and on the phenyl ring, not on those five -- are visible rather than only
summarised.

A longtable, because 84 rows do not fit on a page.
"""

from pathlib import Path
import json

import numpy as np

SCRIPT_DIR = Path(__file__).resolve().parent
RESULT_JSON = (SCRIPT_DIR / "outputs"
               / "01_gbci_s1_grad_check_631g_all_h1e4.json")
OUTPUT_TEX = SCRIPT_DIR / "outputs" / "13_full_gradient_table.tex"
# Written by 10_make_molecule_figure.py; keeps the table, the main-text table
# and the figure on one set of atom labels.
LABELS_JSON = SCRIPT_DIR / "outputs" / "10_atom_labels.json"

STEP_BOHR = 1.0e-4
AXES = "xyz"


def grouped(value, digits=8):
    """Fixed-point LaTeX math with the decimals in groups of three.

    e.g. 0.00346136 -> $\\phantom{-}0.003\\,461\\,36$. Plain spaces collapse in
    math mode, so the separator has to be a thin space, and positive numbers
    take a phantom minus so the decimal points line up.
    """
    text = f"{value:.{digits}f}"
    sign = "-" if text.startswith("-") else r"\phantom{-}"
    integer, fraction = text.lstrip("-").split(".")
    chunks = [fraction[i:i + 3] for i in range(0, len(fraction), 3)]
    return f"${sign}{integer}." + r"\,".join(chunks) + "$"


def sci(value, digits=3, signed=True):
    """LaTeX math in scientific notation, e.g. $-5.621 \\times 10^{-8}$."""
    fmt = f"{value:+.{digits}e}" if signed else f"{value:.{digits}e}"
    mantissa, exponent = fmt.split("e")
    return f"${mantissa} \\times 10^{{{int(exponent)}}}$"


def header(caption=None):
    """Column titles; with ``caption`` for the first page, without for the rest."""
    lines = []
    if caption is not None:
        lines.append(rf"\caption{{{caption}}}\\")
    lines += [
        r"\hline",
        r"Atom & Comp. & Analytic & Numerical & Difference \\",
        r" & & (hartree/bohr) & (hartree/bohr) & (hartree/bohr) \\",
        r"\hline",
    ]
    return lines


def main():
    result = json.loads(RESULT_JSON.read_text())
    if not LABELS_JSON.exists():
        raise RuntimeError(f"run 10_make_molecule_figure.py first to write "
                           f"{LABELS_JSON}")
    labels = {int(k): v for k, v in json.loads(LABELS_JSON.read_text()).items()}
    analytic = np.asarray(result["analytic_gradient"])

    records = sorted(result["displacements"], key=lambda r: (r["atom"], r["axis"]))
    if len(records) != 84:
        raise RuntimeError(f"expected all 28 atoms (84 components), "
                           f"got {len(records)}")

    rows = [(labels[r["atom"]], AXES[r["axis"]],
             analytic[r["atom"]][r["axis"]], r["numerical"],
             analytic[r["atom"]][r["axis"]] - r["numerical"])
            for r in records]
    diffs = np.array([r[4] for r in rows])

    caption = (
        "Analytic and numerical gradients of the $S_1$ state of "
        "3-hydroxyflavone for every Cartesian component, computed with "
        "GBCI(4e,4o)/6-31G at the B3LYP/6-31G(d) ground-state minimum. "
        f"Central differences use a step of ${STEP_BOHR:g}\\,a_0$ with the "
        "grouped-bath assignment frozen to that of the reference geometry and "
        "the bath orbitals of every point semicanonicalized. Atom labels "
        "follow Figure~\\ref{fig:3hf-structure}.")

    lines = [
        r"% Generated by test/3hf/gbci/13_make_full_gradient_table.py",
        r"% Requires \usepackage{longtable}; plain \hline rules.",
        r"\begin{longtable}{llccc}",
    ]
    lines += [f"  {line}" for line in header(caption)]
    lines.append(r"  \endfirsthead")
    lines += [f"  {line}" for line in header()]
    lines.append(r"  \endhead")

    width = max(len(r[0]) for r in rows)
    for k, (atom, axis, g, n, d) in enumerate(rows):
        label = atom if k == 0 or rows[k - 1][0] != atom else ""
        last_of_atom = k + 1 == len(rows) or rows[k + 1][0] != atom
        end = r"\\[2pt]" if last_of_atom and k + 1 != len(rows) else r"\\"
        lines.append(f"  {label:<{width}} & ${axis}$ & {grouped(g)} & "
                     f"{grouped(n)} & {sci(d)} {end}")

    lines.append(r"  \hline")
    summary = [
        ("Maximum absolute difference", float(np.abs(diffs).max())),
        ("Root-mean-square difference", float(np.sqrt((diffs ** 2).mean()))),
        (r"Net torque $|\sum_A \mathbf{R}_A \times \mathbf{g}_A|$ (hartree)",
         float(result["torque"])),
    ]
    for label, value in summary:
        lines.append(f"  \\multicolumn{{4}}{{l}}{{{label}}} & "
                     f"{sci(value, signed=False)} \\\\")
    lines += [r"  \hline", r"\end{longtable}"]

    OUTPUT_TEX.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\nSaved {OUTPUT_TEX}")


if __name__ == "__main__":
    main()
