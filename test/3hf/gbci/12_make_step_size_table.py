"""LaTeX table of the finite-difference step-size dependence, for the SI.

Collects the analytic-versus-numerical comparisons of the GBCI(4e,4o)/6-31G S1
gradient at the step sizes that were run, and reports only the two summary
numbers: the largest absolute difference over the 15 displaced components and
their root-mean-square.

The step size is given here rather than read from the JSON: in combine mode the
script records ``step_bohr`` from the reference run, not from the finite
difference, so that field is 1e-4 in every file.

Two things are recomputed rather than read. The analytic gradient comes from
``25_tight_gradient_fixed.json``: the combines ran against a reference whose
bath came back from Newton SOSCF non-semicanonical, worth 2e-04 in the
gradient (see GRADIENT_INVESTIGATION.md). The maxima and RMS values follow
from it, so ``max_abs_difference`` and ``rms_difference`` in each file are not
used. The numerical side needs no correction -- the GBCI energy depends on the
bath only through its spaces.

Every run listed uses the same settings: tight FAS-SCF (``conv_tol_grad``
1e-11), no bath cache, and ``--freeze-groups``. The four-point stencil has no
campaign under those settings, so that row is gone.
"""

from pathlib import Path
import argparse
import json

import numpy as np

SCRIPT_DIR = Path(__file__).resolve().parent
OUT = SCRIPT_DIR / "outputs"
OUTPUT_TEX = OUT / "12_step_size_table.tex"

FIXED_JSON = OUT / "25_tight_gradient_fixed.json"

# (step in bohr, stencil, result file). All tight + frozen, 15 components,
# compared against the same semicanonicalized analytic gradient.
RUNS = [
    (1.0e-4, 2, "01_gbci_s1_grad_check_631g_tight_frozen_h1e4.json"),
    (2.5e-4, 2, "01_gbci_s1_grad_check_631g_tight_frozen_h25e4.json"),
    (5.0e-4, 2, "01_gbci_s1_grad_check_631g_tight_frozen_h5e4.json"),
    (1.0e-3, 2, "01_gbci_s1_grad_check_631g_tight_frozen_h1e3.json"),
]


def sci(value, digits=3):
    mantissa, exponent = f"{value:.{digits}e}".split("e")
    return f"${mantissa} \\times 10^{{{int(exponent)}}}$"


def step_text(value):
    """Step size as a tidy power of ten, e.g. 2.5e-4 -> $2.5 \\times 10^{-4}$."""
    mantissa, exponent = f"{value:.1e}".split("e")
    mantissa = mantissa.rstrip("0").rstrip(".")
    return f"${mantissa} \\times 10^{{{int(exponent)}}}$"


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--with-four-point", action="store_true",
                    help="not available: no four-point campaign has been run "
                         "under the tight, frozen, uncached settings")
    args = ap.parse_args()
    if args.with_four_point:
        raise RuntimeError(
            "the four-point stencil was only run under the earlier settings, "
            "whose finite-difference floor was 1.4e-06 rather than 1.0e-07; "
            "mixing it into this table would compare different references. "
            "Run --mode fd --stencil 4 with --freeze-groups --no-gbci-cache "
            "--fasscf-conv-tol-grad 1e-11 first.")

    analytic = np.asarray(
        json.loads(FIXED_JSON.read_text())["runs"][1]["analytic"])

    rows = []
    for step, stencil, name in RUNS:
        data = json.loads((OUT / name).read_text())
        diffs = np.array([analytic[r["atom"]][r["axis"]] - r["numerical"]
                          for r in data["displacements"]])
        rows.append((step, stencil, diffs.size,
                     float(np.abs(diffs).max()),
                     float(np.sqrt((diffs ** 2).mean()))))

    counts = {r[2] for r in rows}
    if counts != {15}:
        raise RuntimeError(f"expected 15 components in every run, got {counts}")

    lines = [
        r"% Generated by test/3HF/gbci/12_make_step_size_table.py",
        r"% Plain \hline rules; requires \usepackage{multirow}.",
        r"\begin{table}[htbp]",
        r"  \centering",
        r"  \caption{",
        r"  Dependence of the agreement between the analytic and the numerical",
        r"  gradient on the finite-difference step size, for the $S_1$ state of",
        r"  3-hydroxyflavone computed with GBCI(4e,4o)/6-31G at the",
        r"  B3LYP/6-31G(d) ground-state minimum. Each entry summarises the same",
        r"  15 Cartesian components, obtained from central differences with the",
        r"  grouped-bath assignment frozen to that of the reference geometry and",
        r"  the bath orbitals of every point semicanonicalized.",
        r"  }",
        r"  \label{tab:si_3hf_step_size}",
        r"  \begin{tabular}{" + ("cccc" if args.with_four_point else "ccc") + "}",
        r"    \hline",
    ]
    if not args.with_four_point:
        lines += [
            r"    \multirow{2}{*}{Step size $h$ ($a_0$)} &",
            r"    \multicolumn{1}{c}{Maximum difference} &",
            r"    \multicolumn{1}{c}{RMS difference} \\",
            r"    & \multicolumn{1}{c}{(hartree/bohr)} & "
            r"\multicolumn{1}{c}{(hartree/bohr)} \\",
        ]
    else:
        lines += [
            r"    \multirow{2}{*}{Step size $h$ ($a_0$)} & "
            r"\multirow{2}{*}{Stencil} &",
            r"    \multicolumn{1}{c}{Maximum difference} &",
            r"    \multicolumn{1}{c}{RMS difference} \\",
            r"    & & \multicolumn{1}{c}{(hartree/bohr)} & "
            r"\multicolumn{1}{c}{(hartree/bohr)} \\",
        ]
    lines.append(r"    \hline")
    for step, stencil, _, max_abs, rms in rows:
        stencil_cell = f" & {stencil}-point" if args.with_four_point else ""
        lines.append(f"    {step_text(step)}{stencil_cell} & {sci(max_abs)} & "
                     f"{sci(rms)} " + r"\\")
    lines += [r"    \hline", r"  \end{tabular}", r"\end{table}"]

    OUTPUT_TEX.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\nSaved {OUTPUT_TEX}")


if __name__ == "__main__":
    main()
