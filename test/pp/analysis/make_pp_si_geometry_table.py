"""Supporting-information table of the six optimized 4-(1-pyrrolyl)-pyridine geometries.

The six structures the manuscript discusses are not stored as standalone
``*_optimized.xyz`` files: each one is an endpoint of a path that some other
script already wrote.  The S0 structures are image 0 of the interpolated
ground-state-to-planar segment built by ``../pes/pp_s1_pes_build_images.py``,
and the planar and TICT structures are images 0 and 8 of the NEB bands run by
``../casci/pp_casci_S1_neb.py`` and ``../gbci/pp_gbci_S1_planar_tict_neb.py``.
Reading the table out of those files rather than retyping it is the point of
this script: the published coordinates then cannot drift away from the paths
whose energies Figure 4 plots.

Usage::

    python make_pp_si_geometry_table.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

SCRIPT_PATH = Path(__file__).resolve()
SCRIPT_DIR = SCRIPT_PATH.parent
REPO_ROOT = SCRIPT_DIR.parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from utils.latex_tables import geometry_longtable  # noqa: E402

DEFAULT_OUTPUT = REPO_ROOT / "test" / "supporting_information_geometries.tex"

# (heading, path relative to test/pp).  The NEB bands run planar -> TICT, so
# image 000 is the planar end and image 008 the twisted one.
GEOMETRIES = [
    (
        r"PP CASCI S$_0$",
        "pes/pp_s1_pes_image_outputs/casci_ground_to_planar/"
        "pp_s1_pes_casci_ground_to_planar_000.xyz",
    ),
    (
        r"PP CASCI S$_1$ planar",
        "casci/pp_casci_S1_neb_outputs/pp_casci_S1_neb_000.xyz",
    ),
    (
        r"PP CASCI S$_1$ TICT",
        "casci/pp_casci_S1_neb_outputs/pp_casci_S1_neb_008.xyz",
    ),
    (
        r"PP GBCI S$_0$",
        "pes/pp_s1_pes_image_outputs/gbci_ground_to_planar/"
        "pp_s1_pes_gbci_ground_to_planar_000.xyz",
    ),
    (
        r"PP GBCI S$_1$ planar",
        "gbci/pp_gbci_S1_planar_tict_neb_outputs/pp_gbci_S1_planar_tict_neb_000.xyz",
    ),
    (
        r"PP GBCI S$_1$ TICT",
        "gbci/pp_gbci_S1_planar_tict_neb_outputs/pp_gbci_S1_planar_tict_neb_008.xyz",
    ),
]

CAPTION = "Optimized Cartesian coordinates for PP structures."
LABEL = "tab:si_pp_geometries"


def read_xyz(path: Path) -> tuple[list[str], np.ndarray]:
    """Symbols and coordinates of an extended-XYZ file.

    The NEB images carry forces in columns 4-6; only the first three are read,
    so the plain and extended forms parse the same way.
    """
    lines = path.read_text().splitlines()
    natom = int(lines[0].split()[0])
    symbols, coords = [], []
    for line in lines[2:2 + natom]:
        fields = line.split()
        symbols.append(fields[0])
        coords.append([float(v) for v in fields[1:4]])
    return symbols, np.asarray(coords)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    pp_root = SCRIPT_DIR.parent

    groups = []
    for heading, relative in GEOMETRIES:
        path = pp_root / relative
        if not path.exists():
            raise SystemExit(f"{path} not found")
        symbols, coords = read_xyz(path)
        groups.append((heading, symbols, coords))
        print(f"{heading:28s} <- test/pp/{relative}")

    body = geometry_longtable(groups, CAPTION, LABEL, header="Geometry")
    head = (
        "% Cartesian coordinates in Angstrom.\n"
        f"% Generated by {SCRIPT_PATH.relative_to(REPO_ROOT)}\n"
        "% Requires: \\usepackage{longtable}\n"
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(head + body, encoding="utf-8")
    print(f"\nwrote {args.output}")


if __name__ == "__main__":
    main()
